    static final class Technique {
        String id, name, en, tagline, about, benefits, warning, pattern;
        int cat, color, rounds, mode;
        final ArrayList<Phase> round = new ArrayList<>();
        String[] how;

        float roundSeconds() {
            float s = 0;
            for (Phase p : round) s += p.type == OPEN ? 60 : p.sec;
            return s;
        }

        int minutes(int r) {
            return Math.max(1, Math.round(roundSeconds() * r / 60f));
        }
    }

    static Phase ph(int t, float s) {
        String l;
        switch (t) {
            case IN: l = "שאיפה"; break;
            case IN2: l = "עוד שאיפה"; break;
            case HOLD: l = "החזק"; break;
            case OUT: l = "נשיפה"; break;
            case HOLD_OUT: l = "ריק · החזק"; break;
            default: l = "עצירה";
        }
        return new Phase(t, s, l, null);
    }

    static Phase ph(int t, float s, String label, String sub) {
        return new Phase(t, s, label, sub);
    }

