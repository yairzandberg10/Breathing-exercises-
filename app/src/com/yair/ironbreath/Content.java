    static final class Routine {
        String name, en, sub;
        int color, image;
        String[] poses;
        int[] secs;

        int total() {
            int s = 0;
            for (int x : secs) s += x;
            return s;
        }
    }

    static final ArrayList<Routine> ROUTINES = new ArrayList<>();

    private static void routine(String name, String en, String sub, int color, int image, Object... data) {
        Routine r = new Routine();
        r.name = name;
        r.en = en;
        r.sub = sub;
        r.color = color;
        r.image = image;
        int n = data.length / 2;
        r.poses = new String[n];
        r.secs = new int[n];
        for (int i = 0; i < n; i++) {
            r.poses[i] = (String) data[i * 2];
            r.secs[i] = (Integer) data[i * 2 + 1];
        }
        ROUTINES.add(r);
    }

