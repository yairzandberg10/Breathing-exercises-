    // ------------------------------------------------------------------ meditation
    static final class Meditation {
        String title, sub, en;
        int color, image;
        String[] steps;
        int[] secs;

        int total() {
            int s = 0;
            for (int x : secs) s += x;
            return s;
        }
    }

    static final ArrayList<Meditation> MEDITATIONS = new ArrayList<>();

    private static void med(String title, String en, String sub, int color, int image, Object... data) {
        Meditation m = new Meditation();
        m.title = title;
        m.en = en;
        m.sub = sub;
        m.color = color;
        m.image = image;
        int n = data.length / 2;
        m.steps = new String[n];
        m.secs = new int[n];
        for (int i = 0; i < n; i++) {
            m.secs[i] = (Integer) data[i * 2];
            m.steps[i] = (String) data[i * 2 + 1];
        }
        MEDITATIONS.add(m);
    }

